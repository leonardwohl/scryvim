local helpers = require('helpers')
local markdown = require('scryvim.markdown')

describe('markdown', function()
  local data

  before_each(function()
    helpers.load_fixture()
    helpers.block_network()
    data = require('scryvim.data')
  end)

  local function render(lines, opts)
    return markdown.render(lines, vim.tbl_extend('keep', opts or {}, { lookup = data.get, title = 'burn' }))
  end

  it('keeps image paths in the card data, without the timestamp', function()
    local bolt = data.get('Lightning Bolt')
    assert.are.equal('front/0/0/00000000-0000-0000-0000-000000000001.jpg', bolt.image)
    local delver = data.get('Delver of Secrets')
    assert.is_nil(delver.image)
    assert.are.equal('front/0/0/00000000-0000-0000-0000-000000000018.jpg', delver.card_faces[1].image)
    assert.are.equal('back/0/0/00000000-0000-0000-0000-000000000018.jpg', delver.card_faces[2].image)
    assert.is_true(data.current())
  end)

  it('groups cards under sections and the comments above them, with totals', function()
    local nodes = markdown.nodes({
      'Deck',
      '// Burn (otag:burn)',
      '4 Lightning Bolt',
      '2 Fireball',
      '',
      '// Lands',
      '20 Mountain',
      '// cut these (too slow)',
      '',
      'Sideboard',
      '2 Duress',
    })
    local summary = vim.tbl_map(function(n)
      return { n.kind, n.text or (n.entries and #n.entries), n.total }
    end, nodes)
    assert.are.same({
      { 'heading', 'Deck', 26 },
      { 'heading', 'Burn', 6 },
      { 'cards', 2 },
      { 'heading', 'Lands', 20 },
      { 'cards', 1 },
      { 'note', 'cut these (too slow)' },
      { 'heading', 'Sideboard', 2 },
      { 'cards', 1 },
    }, summary)
    assert.are.equal('otag:burn', nodes[2].query)
  end)

  it('gathers SB: cards outside a sideboard under a Sideboard heading', function()
    local nodes = markdown.nodes({ '4 Lightning Bolt', 'SB: 2 Duress', '20 Mountain' })
    assert.are.same({ 'Lightning Bolt', 'Mountain' }, {
      nodes[1].entries[1].name,
      nodes[1].entries[2].name,
    })
    assert.are.same({ 'heading', 'Sideboard', 2 }, { nodes[2].kind, nodes[2].text, nodes[2].total })
    assert.are.equal('Duress', nodes[3].entries[1].name)
  end)

  it('renders images, links and counts in a grid', function()
    local out = render({ 'Deck', '4 lightning bolt', '1 Delver of Secrets', '2 Fire // Ice', '1 Nope' }, {
      columns = 2,
      width = 100,
    })
    assert.matches('^<!%-%- Generated by scryvim from burn%. ', out)
    assert.matches('\n# burn\n', out, 1, false)
    assert.matches('\n8 cards · 0 lands · 8 nonlands\n', out, 1, true)
    assert.matches('\n## Deck · 8\n', out, 1, true)
    -- The card data's spelling, linked to its Scryfall page.
    assert.matches(
      '<td align="center" valign="top"><a href="https://scryfall.com/card/fix/1/lightning-bolt">'
        .. '<img src="https://cards.scryfall.io/normal/front/0/0/00000000-0000-0000-0000-000000000001.jpg" '
        .. 'width="100" alt="Lightning Bolt"></a><br><b>4</b> Lightning Bolt</td>',
      out,
      1,
      true
    )
    -- A double-faced card shows its front face.
    assert.matches('normal/front/0/0/00000000-0000-0000-0000-000000000018.jpg', out, 1, true)
    assert.matches('<b>1</b> Nope<br><sub>unknown card</sub></td>', out, 1, true)
    -- Two cards a row.
    local _, rows = out:gsub('<tr>', '')
    assert.are.equal(2, rows)
  end)

  it('shows mana symbols and leaves count cards to the summary', function()
    local out = render({ '// count cards', '// count mana symbols', '4 Lightning Bolt', '2 Counterspell' })
    assert.matches(
      '\n<img src="https://svgs.scryfall.io/card-symbols/U.svg" width="16" alt="{U}"> 4 &nbsp; '
        .. '<img src="https://svgs.scryfall.io/card-symbols/R.svg" width="16" alt="{R}"> 4\n',
      out,
      1,
      true
    )
    local _, n = out:gsub('6 cards', '')
    assert.are.equal(1, n)
  end)

  it('notes the sideboard size and escapes comment text', function()
    local out = render({ '4 Lightning Bolt', '// *keep* <these> & #2', '', 'Sideboard', '2 Duress' })
    assert.matches('4 cards · 0 lands · 4 nonlands · 2 in sideboard', out, 1, true)
    assert.matches('\n> \\*keep\\* &lt;these&gt; &amp; \\#2\n', out, 1, true)
  end)

  it('renders the same file again for an unchanged deck', function()
    local lines = { 'Deck', '4 Lightning Bolt', '20 Mountain' }
    assert.are.equal(render(lines), render(lines))
  end)

  describe('write', function()
    local dir

    before_each(function()
      dir = vim.fn.tempname()
      vim.fn.mkdir(dir, 'p')
    end)

    local function write_file(path, s)
      local f = assert(io.open(path, 'wb'))
      f:write(s)
      f:close()
    end

    local function read_file(path)
      local f = io.open(path, 'rb')
      if not f then
        return nil
      end
      local s = f:read('*a')
      f:close()
      return s
    end

    it('writes the page next to the deck, then finds it up to date', function()
      local deck = dir .. '/burn.deck'
      write_file(deck, '4 Lightning Bolt\n20 Mountain\n')
      assert.are.equal(dir .. '/burn.md', markdown.target(deck))
      assert.are.equal('written', markdown.write(deck, { lookup = data.get }))
      assert.matches('# burn', read_file(dir .. '/burn.md'), 1, true)
      assert.are.equal('unchanged', markdown.write(deck, { lookup = data.get }))
      assert.are.equal('unchanged', markdown.write(deck, { lookup = data.get, check = true }))
    end)

    it('reports an outdated page with check, without writing it', function()
      local deck = dir .. '/burn.deck'
      write_file(deck, '4 Lightning Bolt\n')
      markdown.write(deck, { lookup = data.get })
      local before = read_file(dir .. '/burn.md')
      write_file(deck, '4 Lightning Bolt\n2 Fireball\n')
      assert.are.equal('outdated', markdown.write(deck, { lookup = data.get, check = true }))
      assert.are.equal(before, read_file(dir .. '/burn.md'))
    end)

    it('renders given lines instead of the file', function()
      local deck = dir .. '/burn.deck'
      assert.are.equal('written', markdown.write(deck, { lookup = data.get, lines = { '3 Fireball' } }))
      assert.matches('<b>3</b> Fireball', read_file(dir .. '/burn.md'), 1, true)
    end)

    it('never overwrites a file scryvim did not make', function()
      local deck = dir .. '/README.deck'
      write_file(deck, '4 Lightning Bolt\n')
      write_file(dir .. '/README.md', '# My decks\n')
      local status, err = markdown.write(deck, { lookup = data.get })
      assert.is_nil(status)
      assert.matches('not made by scryvim', err)
      assert.are.equal('# My decks\n', read_file(dir .. '/README.md'))
    end)

    it('fails on a missing deck', function()
      local status, err = markdown.write(dir .. '/nope.deck', { lookup = data.get })
      assert.is_nil(status)
      assert.matches('cannot read', err)
    end)
  end)

  describe(':Scryvim render', function()
    local scryvim = require('scryvim')
    local headless, notify = scryvim._headless, vim.notify
    local messages

    before_each(function()
      scryvim._headless = function()
        return false
      end
      messages = {}
      vim.notify = function(msg, level)
        messages[#messages + 1] = { msg, level }
      end
    end)

    after_each(function()
      scryvim._headless, vim.notify = headless, notify
    end)

    it('renders the current buffer, and files given', function()
      local dir = vim.fn.tempname()
      vim.fn.mkdir(dir, 'p')
      local buf = vim.api.nvim_create_buf(true, false)
      vim.api.nvim_buf_set_name(buf, dir .. '/a.deck')
      vim.api.nvim_buf_set_lines(buf, 0, -1, false, { '4 Lightning Bolt' })
      vim.api.nvim_set_current_buf(buf)
      assert.is_true(scryvim.render())
      assert.matches('wrote', messages[1][1])
      assert.is_true(vim.uv.fs_stat(dir .. '/a.md') ~= nil)

      local f = assert(io.open(dir .. '/b.deck', 'wb'))
      f:write('2 Fireball\n')
      f:close()
      assert.is_false(scryvim.render({ files = { dir .. '/*.deck' }, check = true }))
      assert.matches('b%.md is out of date', messages[#messages][1])
      assert.is_true(scryvim.render({ files = { dir .. '/*.deck' } }))
      assert.is_true(scryvim.render({ files = { dir .. '/*.deck' }, check = true }))
      vim.api.nvim_buf_delete(buf, { force = true })
    end)

    it('refuses while the card data has no image links', function()
      data.index({ { name = 'Lightning Bolt' } })
      assert.is_false(scryvim.render({ files = { 'x.deck' } }))
      assert.matches('render:', messages[1][1])
    end)
  end)
end)
