--- Decklist -> a Markdown page of card images, for reading a deck (and its
--- diffs) on GitHub. `:Scryvim render` writes it next to the deck, named
--- after it: `burn.deck` -> `burn.md`.
---
--- The page follows the decklist: each section (`Deck`, `Sideboard`, ...)
--- and each comment directly above cards becomes a heading with its card
--- total, and the cards under it a grid of images with their counts.
--- The page opens with the deck's size, and `// count mana symbols` lines
--- become its mana symbols; other comments become notes. `SB:` cards outside a sideboard section are
--- gathered under a Sideboard heading at the end.
---
--- Images link to Scryfall's image server rather than being saved, and the
--- output depends only on the decklist and the card data, so rendering an
--- unchanged deck again gives the same file.
local count = require('scryvim.count')
local parse = require('scryvim.parse')
local render = require('scryvim.render')
local symbols = require('scryvim.symbols')

local M = {}

M.IMAGE_URL = 'https://cards.scryfall.io/normal/'
M.SYMBOL_URL = 'https://svgs.scryfall.io/card-symbols/'

--- The first line of every generated file. A file that doesn't start with
--- it is never overwritten.
M.MARKER = '<!-- Generated by scryvim'

local function html(s)
  return (s:gsub('[&<>"]', { ['&'] = '&amp;', ['<'] = '&lt;', ['>'] = '&gt;', ['"'] = '&quot;' }))
end

-- Text for a heading or paragraph: HTML-escaped, with Markdown's inline
-- markers escaped so a comment's `*` or `_` shows as written.
local function text(s)
  return (html(s):gsub('([\\`*_%[%]#|~])', '\\%1'))
end

local function comment_text(line)
  return vim.trim(line:match('^%s*//(.*)$') or line:match('^%s*#(.*)$') or line)
end

-- `front/6/d/<id>.jpg` for the card, or its front face.
local function image(card)
  if card.image then
    return card.image
  end
  local face = card.card_faces and card.card_faces[1]
  return face and face.image
end

-- The card's Scryfall page, without the `?utm_source=api` query.
local function page(card)
  local uri = card.scryfall_uri
  return type(uri) == 'string' and uri:match('^[^?#]+') or nil
end

-- The name as the card data spells it (the face's, for a face name), or
-- as written when the card is unknown.
local function display_name(entry, card)
  local want = entry.name:lower()
  if card then
    if card.name:lower() == want then
      return card.name
    end
    for _, face in ipairs(card.card_faces or {}) do
      if face.name and face.name:lower() == want then
        return face.name
      end
    end
  end
  return entry.name
end

-- `printing` (the line's set and number, looked up) takes the place of
-- the card data's default printing.
local function cell(entry, card, printing, width)
  local caption = ('<b>%d</b> %s'):format(entry.count, html(display_name(entry, card)))
  local shown = printing or card
  local img = shown and image(shown)
  if not img then
    return ('<td align="center" valign="top">%s<br><sub>%s</sub></td>'):format(
      caption,
      card and 'no image' or 'unknown card'
    )
  end
  local tag = ('<img src="%s%s" width="%d" alt="%s">'):format(M.IMAGE_URL, img, width, html(shown.name))
  local link = page(shown)
  if link then
    tag = ('<a href="%s">%s</a>'):format(html(link), tag)
  end
  return ('<td align="center" valign="top">%s<br>%s</td>'):format(tag, caption)
end

local function grid(entries, lookup, opts, out)
  out[#out + 1] = '<table>'
  for i, e in ipairs(entries) do
    if (i - 1) % opts.columns == 0 then
      if i > 1 then
        out[#out + 1] = '</tr>'
      end
      out[#out + 1] = '<tr>'
    end
    out[#out + 1] = cell(e, lookup(e.name), opts.printing and opts.printing(e) or nil, opts.width)
  end
  out[#out + 1] = '</tr>'
  out[#out + 1] = '</table>'
  out[#out + 1] = ''
end

local function mana_text(totals)
  local parts = {}
  for _, t in ipairs(symbols.TYPES) do
    local v = totals[t]
    if v and v > 0 then
      parts[#parts + 1] = ('<img src="%s%s.svg" width="16" alt="{%s}"> %g'):format(M.SYMBOL_URL, t, t, v)
    end
  end
  return #parts > 0 and table.concat(parts, ' &nbsp; ') or 'no mana symbols'
end

local function cards_text(stats)
  local parts = { render.plural(stats.cards, 'card') }
  if stats.lands then
    parts[#parts + 1] = render.plural(stats.lands, 'land')
    parts[#parts + 1] = render.plural(stats.cards - stats.lands, 'nonland')
  end
  return table.concat(parts, ' · ')
end

local function sum(entries)
  local n = 0
  for _, e in ipairs(entries) do
    n = n + e.count
  end
  return n
end

--- The decklist `lines` as the page's nodes, in order: `heading` (`level`
--- 2 for sections, 3 for comments above cards; `query` for count lines),
--- `cards` (`entries`), `note` and `stats` (`'mana'`).
---@param lines string[]
---@return table[]
function M.nodes(lines)
  local parsed = {}
  for i, line in ipairs(lines) do
    parsed[i] = parse.parse(line)
  end
  local nodes, sb = {}, {}
  local group, side = nil, false
  for i, p in ipairs(parsed) do
    if p.kind == 'card' then
      if parse.is_sb(p) and not side then
        sb[#sb + 1] = { name = p.name, count = p.count, set = p.set, number = p.number }
      else
        if not group then
          group = { kind = 'cards', entries = {} }
          nodes[#nodes + 1] = group
        end
        group.entries[#group.entries + 1] = { name = p.name, count = p.count, set = p.set, number = p.number }
      end
    else
      group = nil
      if p.kind == 'section' then
        local name = p.name:match('^[Ss][Bb]:?$') and 'Sideboard' or p.name
        side = parse.SIDE_SECTIONS[name:lower()] or false
        nodes[#nodes + 1] = { kind = 'heading', level = 2, text = name }
      -- `// count cards` is left out: the page's summary line has it.
      elseif p.kind == 'comment' and p.count ~= 'cards' then
        local above = parsed[i + 1] and parsed[i + 1].kind == 'card'
        if p.count == 'mana' then
          nodes[#nodes + 1] = { kind = 'stats', stats = 'mana' }
        elseif above then
          local label = p.count == 'query' and (p.label or p.query) or comment_text(lines[i])
          nodes[#nodes + 1] = { kind = 'heading', level = 3, text = label, query = p.query }
        elseif comment_text(lines[i]) ~= '' then
          nodes[#nodes + 1] = { kind = 'note', text = comment_text(lines[i]) }
        end
      end
    end
  end
  if #sb > 0 then
    nodes[#nodes + 1] = { kind = 'heading', level = 2, text = 'Sideboard' }
    nodes[#nodes + 1] = { kind = 'cards', entries = sb }
  end
  -- Totals: a level 3 heading counts the cards right under it, a section
  -- everything up to the next section.
  for i, n in ipairs(nodes) do
    if n.kind == 'heading' then
      n.total = 0
      for j = i + 1, #nodes do
        local m = nodes[j]
        if m.kind == 'heading' and (m.level <= n.level or n.level == 3) then
          break
        elseif m.kind == 'cards' then
          n.total = n.total + sum(m.entries)
          if n.level == 3 then
            break
          end
        end
      end
    end
  end
  return nodes
end

--- Render the decklist `lines` as Markdown.
---@param lines string[]
--- `opts.printing(entry)` gives the looked-up printing for an entry with a
--- set code (`entry.set`, `entry.number`), whose image then replaces the
--- default one.
---@param opts { lookup: fun(name: string): table|nil, printing?: fun(entry: table): table|nil, title: string, source?: string, columns?: integer, width?: integer }
---@return string
function M.render(lines, opts)
  opts = vim.tbl_extend('keep', opts, { columns = 5, width = 140 })
  local lookup = opts.lookup
  local main = count.entries(lines, lookup)
  local all = count.entries(lines, lookup, true)
  local stats = count.stats(main, lookup)
  local side = sum(all) - stats.cards

  local out = {
    ('%s from %s. Edit the decklist and run :Scryvim render instead of editing this file. -->'):format(
      M.MARKER,
      html(opts.source or opts.title)
    ),
    '',
    '# ' .. text(opts.title),
    '',
    cards_text(stats) .. (side > 0 and (' · %d in sideboard'):format(side) or ''),
    '',
  }
  for _, n in ipairs(M.nodes(lines)) do
    if n.kind == 'heading' then
      out[#out + 1] = ('%s %s · %d'):format(('#'):rep(n.level), text(n.text), n.total)
      out[#out + 1] = ''
      if n.query and n.query ~= n.text then
        out[#out + 1] = '<sub>' .. html(n.query) .. '</sub>'
        out[#out + 1] = ''
      end
    elseif n.kind == 'cards' then
      grid(n.entries, lookup, opts, out)
    elseif n.kind == 'note' then
      out[#out + 1] = '> ' .. text(n.text)
      out[#out + 1] = ''
    elseif n.kind == 'stats' then
      out[#out + 1] = mana_text(stats.mana or {})
      out[#out + 1] = ''
    end
  end
  while out[#out] == '' do
    out[#out] = nil
  end
  return table.concat(out, '\n') .. '\n'
end

--- The Markdown file for the deck at `path`: the same name, `.md`.
---@param path string
---@return string
function M.target(path)
  return vim.fn.fnamemodify(path, ':r') .. '.md'
end

local function read(path)
  local f = io.open(path, 'rb')
  if not f then
    return nil
  end
  local s = f:read('*a')
  f:close()
  return s
end

--- The lines of the file at `path`, or nil and an error.
---@param path string
---@return string[]|nil, string|nil
function M.read_lines(path)
  local s = read(path)
  if not s then
    return nil, 'cannot read ' .. path
  end
  return vim.split((s:gsub('\r', '')), '\n', { plain = true })
end

--- Render the deck at `path` (from `lines`, or the file) and write it to
--- its Markdown file, unless that is already up to date. With `check`,
--- nothing is written.
---
--- Returns `'written'`, `'unchanged'` or (with `check`) `'outdated'`, or
--- nil and an error.
---@param path string
---@param opts { lookup: fun(name: string): table|nil, printing?: fun(entry: table): table|nil, lines?: string[], check?: boolean, columns?: integer, width?: integer }
---@return string|nil status, string|nil err
function M.write(path, opts)
  local lines = opts.lines
  if not lines then
    local err
    lines, err = M.read_lines(path)
    if not lines then
      return nil, err
    end
  end
  local target = M.target(path)
  if vim.fn.fnamemodify(target, ':p') == vim.fn.fnamemodify(path, ':p') then
    return nil, path .. ' is already a .md file'
  end
  local name = vim.fn.fnamemodify(path, ':t')
  local out = M.render(lines, {
    lookup = opts.lookup,
    printing = opts.printing,
    title = vim.fn.fnamemodify(path, ':t:r'),
    source = name,
    columns = opts.columns,
    width = opts.width,
  })
  local old = read(target)
  if old == out then
    return 'unchanged'
  end
  if old and old:sub(1, #M.MARKER) ~= M.MARKER then
    return nil, target .. ' exists and was not made by scryvim; not overwriting it'
  end
  if opts.check then
    return 'outdated'
  end
  local tmp = target .. '.tmp'
  local f, err = io.open(tmp, 'wb')
  if not f then
    return nil, err
  end
  f:write(out)
  f:close()
  local ok, rerr = os.rename(tmp, target)
  if not ok then
    os.remove(tmp)
    return nil, rerr
  end
  return 'written'
end

return M
